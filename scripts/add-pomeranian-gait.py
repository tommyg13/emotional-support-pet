"""Add a four-leg walk/trot rig and export 1K embedded textures.
Input: the four-bone blend generated by create-pomeranian-rig.py.
Run Blender --background SOURCE.blend --python scripts/add-pomeranian-gait.py -- OUTPUT.
The editable blend retains full-resolution images; only the GLB uses smaller images.
"""
import bpy,math,os,json,sys
from mathutils import Vector,Quaternion,Matrix
out=sys.argv[sys.argv.index('--')+1] if '--' in sys.argv else '/private/tmp/pomeranian-gait'
os.makedirs(out,exist_ok=True)
mesh=next(o for o in bpy.data.objects if o.type=='MESH');rig=next(o for o in bpy.data.objects if o.type=='ARMATURE')
if 'FrontLUpper' in rig.data.bones:raise RuntimeError('Input already has leg bones; rebuild from the four-bone source instead.')
rig.animation_data.action=None
for p in rig.pose.bones:p.rotation_quaternion=Quaternion();p.location=(0,0,0)
bpy.context.view_layer.objects.active=rig;bpy.ops.object.mode_set(mode='EDIT')
legs={}
for side,x in [('L',-.115),('R',.12)]:
 for kind,hy,ky,fy in [('Front',-.10,-.07,-.14),('Rear',.35,.43,.39)]:
  name=kind+side;hip=Vector((x,hy,.30));knee=Vector((x,ky,.145));foot=Vector((x,fy,.03));legs[name]=(hip,knee,foot)
  upper=rig.data.edit_bones.new(name+'Upper');upper.head=hip;upper.tail=knee;upper.parent=rig.data.edit_bones['Body']
  lower=rig.data.edit_bones.new(name+'Lower');lower.head=knee;lower.tail=foot;lower.parent=upper;lower.use_connect=True
  paw=rig.data.edit_bones.new(name+'Paw');paw.head=foot;paw.tail=foot+Vector((0,-.055,0));paw.parent=lower;paw.use_connect=True
bpy.ops.object.mode_set(mode='OBJECT')
def smooth(a,b,x):
 t=max(0,min(1,(x-a)/(b-a)));return t*t*(3-2*t)
for name in legs:
 for part in ['Upper','Lower','Paw']:mesh.vertex_groups.new(name=name+part)
counts={n:0 for n in legs}
for v in mesh.data.vertices:
 x,y,z=v.co
 side='L'if x<.008 else'R';kind='Front'if y<.15 else'Rear';name=kind+side
 # Keep central belly/coat attached to Body. Only the separate leg columns deform.
 lateral=smooth(.018,.07,abs(x-.008));longitudinal=(1-smooth(-.025,.055,y))if kind=='Front'else smooth(.26,.335,y)
 w=(1-smooth(.15,.30,z))*lateral*longitudinal
 if w<1e-6:continue
 existing={g.group:g.weight for g in v.groups}
 for index,weight in existing.items():mesh.vertex_groups[index].add([v.index],weight*(1-w),'REPLACE')
 lower=1-smooth(.09,.17,z)
 paw=1-smooth(.035,.075,z)
 for part,weight in [('Upper',w*(1-lower)*(1-paw)),('Lower',w*lower*(1-paw)),('Paw',w*paw)]:
  if weight>1e-6:mesh.vertex_groups[name+part].add([v.index],weight,'REPLACE')
 counts[name]+=1
rest={bone.name:bone.matrix_local.copy() for bone in rig.data.bones}
bodyPivot=rest['Body'].translation.copy()
bodyDeform=Matrix.Identity(4)
def reset():
 for p in rig.pose.bones:p.rotation_quaternion=Quaternion();p.location=(0,0,0);p.scale=(1,1,1)
def legpose(name,phase,stride,lift,duty):
 hip,knee,foot=legs[name];l1=(knee-hip).length;l2=(foot-knee).length
 if phase<duty:
  t=phase/duty;offset=-stride/2+stride*t;up=0
 else:
  t=(phase-duty)/(1-duty);offset=stride/2-stride*t;up=lift*math.sin(t*math.pi)**1.4
 target=foot+Vector((0,offset,up));currentHip=bodyDeform@hip;delta=target-currentHip
 distance=min(delta.length,l1+l2-.00001);direction=delta.normalized()
 target=currentHip+direction*distance
 a=(l1*l1-l2*l2+distance*distance)/(2*distance);h=math.sqrt(max(0,l1*l1-a*a))
 preferred=Vector((0,1,0));perpendicular=(preferred-direction*preferred.dot(direction)).normalized()
 newknee=currentHip+direction*a+perpendicular*h
 upperWorld=(knee-hip).rotation_difference(newknee-currentHip)@rest[name+'Upper'].to_quaternion()
 lowerWorld=(foot-knee).rotation_difference(target-newknee)@rest[name+'Lower'].to_quaternion()
 bodyWorld=bodyDeform.to_quaternion()@rest['Body'].to_quaternion()
 for part,parentWorld,desiredWorld,parentName in [
  ('Upper',bodyWorld,upperWorld,'Body'),
  ('Lower',upperWorld,lowerWorld,name+'Upper'),
  ('Paw',lowerWorld,rest[name+'Paw'].to_quaternion(),name+'Lower')]:
  relative=rest[parentName].to_quaternion().inverted()@rest[name+part].to_quaternion()
  pb=rig.pose.bones[name+part];pb.rotation_mode='QUATERNION'
  pb.rotation_quaternion=(parentWorld@relative).inverted()@desiredWorld
 return target
clips=[]
for clip,stride,lift,duty,frames,offsets in [
 ('Walk',.10,.023,.64,25,{'FrontL':0,'RearL':.25,'FrontR':.5,'RearR':.75}),
 ('Trot',.13,.028,.54,17,{'FrontL':0,'RearR':0,'FrontR':.5,'RearL':.5})]:
 reset();action=bpy.data.actions.new(clip);rig.animation_data.action=action
 for frame in range(1,frames+1):
  phase=(frame-1)/(frames-1)
  roll=Quaternion(Vector((0,1,0)),math.radians(.65 if clip=='Walk' else .35)*math.sin(phase*math.tau))
  bodyDeform=Matrix.Translation(bodyPivot)@roll.to_matrix().to_4x4()@Matrix.Translation(-bodyPivot)
  rb=rest['Body'].to_quaternion();rig.pose.bones['Body'].rotation_quaternion=rb.inverted()@roll@rb
  rig.pose.bones['Body'].keyframe_insert('rotation_quaternion',frame=frame,group='Body')
  for name in legs:
   legpose(name,(phase+offsets[name])%1,stride,lift,duty)
   for part in ['Upper','Lower','Paw']:rig.pose.bones[name+part].keyframe_insert('rotation_quaternion',frame=frame,group=name+part)
 track=rig.animation_data.nla_tracks.new();track.name=clip;track.strips.new(clip,1,action);track.mute=True;action.use_fake_user=True;clips.append(clip)
rig.animation_data.action=None;reset();bpy.context.scene.frame_set(1)
rig['purpose']='Head/tail reactions, four planted paw chains and a gentle body weight shift.'
bpy.context.preferences.filepaths.save_version=0
# Keep full resolution editable textures in the art source.
bpy.ops.wm.save_as_mainfile(filepath=out+'/pomeranian-rig.blend')
for im in bpy.data.images:
 if im.size[0]>1024:im.scale(1024,1024);im.pack()
bpy.ops.object.select_all(action='DESELECT');mesh.select_set(True);rig.select_set(True);bpy.context.view_layer.objects.active=rig
bpy.ops.export_scene.gltf(filepath=out+'/pomeranian.glb',export_format='GLB',use_selection=True,export_animations=True,export_animation_mode='ACTIONS',export_skins=True,export_influence_nb=4,export_force_sampling=True)
# Measure deformations at all cycle frames before accepting the prototype.
report={'weighted_leg_vertices':counts,'clips':{},'texture_size':1024}
scene=bpy.context.scene
for clip in clips:
 rig.animation_data.action=bpy.data.actions[clip];peak=1;contact_error=0;paw_tilt=0
 duty=.64 if clip=='Walk' else .54
 offsets={'FrontL':0,'RearL':.25,'FrontR':.5,'RearR':.75}if clip=='Walk'else{'FrontL':0,'RearR':0,'FrontR':.5,'RearL':.5}
 end=25 if clip=='Walk'else 17
 for frame in range(1,26 if clip=='Walk' else 18):
  scene.frame_set(frame);evaluated=mesh.evaluated_get(bpy.context.evaluated_depsgraph_get());deformed=evaluated.to_mesh()
  for edge in mesh.data.edges:
   a,b=edge.vertices;length=(mesh.data.vertices[a].co-mesh.data.vertices[b].co).length
   if length>.002:peak=max(peak,(deformed.vertices[a].co-deformed.vertices[b].co).length/length)
  evaluated.to_mesh_clear()
  for name in legs:
   phase=((frame-1)/(end-1)+offsets[name])%1
   if phase<duty:
    pb=rig.pose.bones[name+'Paw'];contact_error=max(contact_error,abs(pb.head.z-legs[name][2].z));paw_tilt=max(paw_tilt,abs((pb.tail-pb.head).normalized().z))
 report['clips'][clip]={'max_edge_stretch':round(peak,3),'max_stance_height_error':round(contact_error,6),'max_stance_paw_tilt':round(paw_tilt,6)}
with open(out+'/gait-report.json','w')as f:json.dump(report,f,indent=2)
# Render gait extrema from both sides for visual review.
scene.render.engine='BLENDER_EEVEE';scene.render.resolution_x=650;scene.render.resolution_y=650;scene.render.resolution_percentage=100
camera=scene.camera
if not camera:
 data=bpy.data.cameras.new('Gait preview');camera=bpy.data.objects.new('Gait preview',data);scene.collection.objects.link(camera);scene.camera=camera
if not any(o.type=='LIGHT'for o in scene.objects):
 for loc,power in [((2,-3,4),350),((-3,-1,2),200),((0,3,3),250)]:
  data=bpy.data.lights.new('Softbox','AREA');data.energy=power;data.shape='DISK';data.size=3
  light=bpy.data.objects.new('Softbox',data);scene.collection.objects.link(light);light.location=loc;light.rotation_euler=(Vector((0,0,.45))-light.location).to_track_quat('-Z','Y').to_euler()
scene.world.color=(.65,.65,.65)
camera.data.type='ORTHO';camera.data.ortho_scale=1.1
for clip,frame in [('Walk',1),('Walk',7),('Walk',13),('Walk',19),('Trot',1),('Trot',5),('Trot',9)]:
 rig.animation_data.action=bpy.data.actions[clip];scene.frame_set(frame)
 for side in [1,-1]if frame==7 else[1]:
  camera.location=(side*2,-.3,.7);camera.rotation_euler=(Vector((0,.02,.43))-camera.location).to_track_quat('-Z','Y').to_euler();scene.render.filepath=f'{out}/{clip}-{frame}-{side}.png';bpy.ops.render.render(write_still=True)
print('GAIT_REPORT',json.dumps(report))
